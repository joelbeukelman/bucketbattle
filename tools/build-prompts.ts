/**
 * Builds the character prompt matrix from docs/characters/prompt-kit.json:
 *   - docs/characters/PROMPT-MATRIX.md     (every prompt, ready to paste, V7 syntax)
 *   - docs/characters/prompt-matrix.html   (interactive run sheet, published as an Artifact)
 * Usage: pnpm prompts
 *
 * Sheet templates use {LOOK} {IDENTITY} {INSTRUMENT} {STYLE:hero|map|prop}, resolved here.
 * {HERO_SREF} {MAP_SREF} {FACETED_SREF} {CHAR_REF:strong|light} {VERSION} stay as tokens for
 * the page, which fills them per the viewer's Midjourney version and pasted URLs.
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';

type StyleId = 'hero' | 'map' | 'prop';
interface Variant { id: string; label: string; text: string }
interface Sheet { id: string; label: string; why: string; template: string; params: string; charRef: 'strong' | 'light' | null; variants?: Variant[] }
/** One prompt = one image. Sheets with variants (A-pose front/side, six expressions) expand to several shots. */
interface Shot { id: string; label: string; sheet: Sheet; variant?: Variant }
interface Character { id: string; name: string; genre: string; have: string[]; note?: string; look: string; identity: string; instrument: string }
interface Kit { imageBase: string; styleRefs: { hero: string; map: string; faceted: string }; styles: Record<StyleId, string>; sheets: Sheet[]; characters: Character[] }

const dir = 'docs/characters';
const imagesDir = 'docs/references/images';
const kit: Kit = JSON.parse(readFileSync(`${dir}/prompt-kit.json`, 'utf8'));

const fileFor = (c: Character, shotId: string) => `char-${c.id}-${shotId}.jpg`;
const repoUrl = (c: Character, shotId: string) => (c.have.includes(shotId) ? kit.imageBase + fileFor(c, shotId) : null);
/**
 * Character reference: the single-figure front crop (tools/crop-fronts.py) when present. A multi-view
 * turnaround as reference makes Midjourney return lineups instead of one pose or one face.
 */
const charRefUrl = (c: Character) => repoUrl(c, 'front') ?? repoUrl(c, 'turnaround');
const shots: Shot[] = kit.sheets.flatMap((sheet) =>
  sheet.variants ? sheet.variants.map((variant) => ({ id: `${sheet.id}-${variant.id}`, label: variant.label, sheet, variant })) : [{ id: sheet.id, label: sheet.label, sheet }],
);

for (const c of kit.characters)
  for (const s of c.have) if (!existsSync(`${imagesDir}/${fileFor(c, s)}`)) throw new Error(`${c.id} lists "${s}" but ${imagesDir}/${fileFor(c, s)} is missing`);

function assemble(c: Character, shot: Shot): string {
  const s = shot.sheet;
  const text = s.template
    .replace('{VARIANT}', shot.variant?.text ?? '')
    .replace('{LOOK}', c.look)
    .replace('{IDENTITY}', c.identity)
    .replace('{INSTRUMENT}', c.instrument)
    .replace(/\{STYLE:(hero|map|prop)\}/, (_, id: StyleId) => kit.styles[id]);
  return `${text} ${s.params} {VERSION}`;
}

const prompts = Object.fromEntries(kit.characters.map((c) => [c.id, Object.fromEntries(shots.map((sh) => [sh.id, assemble(c, sh)]))]));

// Markdown uses V7 syntax: --oref is the most reliable way to keep a character consistent.
const OW = { strong: 100, light: 25 };
const md = (c: Character, shotId: string) =>
  prompts[c.id]![shotId]!
    .replaceAll('{HERO_SREF}', kit.styleRefs.hero)
    .replaceAll('{MAP_SREF}', kit.styleRefs.map)
    .replaceAll('{FACETED_SREF}', kit.styleRefs.faceted)
    .replace(/\{CHAR_REF:(strong|light)\}/, (_, w: 'strong' | 'light') => `--oref ${charRefUrl(c) ?? `<${c.id} front URL>`} --ow ${OW[w]}`)
    .replace('{VERSION}', '--v 7')
    .replace(/ {2,}/g, ' ');

const total = kit.characters.length * shots.length;
const haveCount = kit.characters.reduce((n, c) => n + shots.filter((sh) => c.have.includes(sh.id)).length, 0);
const lines: string[] = [
  '# Prompt Matrix: starter characters',
  '',
  '_Generated by `pnpm prompts` from `prompt-kit.json`. Edit the JSON, not this file._',
  '',
  `${kit.characters.length} characters × ${shots.length} shots = **${total} prompts** (${haveCount} images in the repo so far). Prompts use Midjourney V7 (\`--v 7\` with \`--oref\`), because V8.x dropped Omni Reference. For V8, use the run sheet's V8 mode: it moves the reference image to the start of the prompt with \`--iw\`.`,
  '',
  '## Run order (per character)',
  ...kit.sheets.map((s, i) => `${i + 1}. **${s.label}**${s.variants ? ` (${s.variants.length} shots: ${s.variants.map((v) => v.label).join(', ')})` : ''}: ${s.why}`),
  '',
  `Style references: hero = REF-005, map = REF-004, plus the rap turnaround as a second hero style reference (it's the closest match to the faceted look).`,
  '',
  '## Matrix',
  '',
  `| Character | ${kit.sheets.map((s, i) => `${i + 1}. ${s.label}`).join(' | ')} |`,
  `|---|${kit.sheets.map(() => '---').join('|')}|`,
  ...kit.characters.map(
    (c) =>
      `| **${c.id}** ${c.name} | ${kit.sheets
        .map((s) => {
          const own = shots.filter((sh) => sh.sheet === s);
          const done = own.filter((sh) => c.have.includes(sh.id)).length;
          return `${done ? `✅ ${done}/${own.length} · ` : ''}[prompts](#${c.id}-${s.id})`;
        })
        .join(' | ')} |`,
  ),
  '',
  `Save results as \`docs/references/images/char-<character>-<sheet>.jpg\` (e.g. \`${fileFor(kit.characters[1]!, 'apose')}\`) and add the sheet to that character's \`have\` list in prompt-kit.json.`,
  '',
];
for (const c of kit.characters) {
  lines.push(`## ${c.id} · ${c.name}`, '');
  if (c.note) lines.push(`> ${c.note}`, '');
  for (const [i, s] of kit.sheets.entries()) {
    lines.push(`<a id="${c.id}-${s.id}"></a>`, `### ${i + 1}. ${s.label}`, '');
    for (const sh of shots.filter((x) => x.sheet === s)) {
      const done = c.have.includes(sh.id) ? ' ✅ in repo' : '';
      lines.push(`**${sh.label}** → \`${fileFor(c, sh.id)}\`${done}`, '```', md(c, sh.id), '```', '');
    }
  }
}
writeFileSync(`${dir}/PROMPT-MATRIX.md`, lines.join('\n'));

const data = {
  styleRefs: kit.styleRefs,
  sheets: kit.sheets.map(({ id, label, why, charRef }) => ({ id, label, why, charRef, shots: shots.filter((sh) => sh.sheet.id === id).map((sh) => ({ id: sh.id, label: sh.label })) })),
  characters: kit.characters.map((c) => ({
    id: c.id,
    name: c.name,
    genre: c.genre,
    note: c.note ?? '',
    have: c.have,
    ref: charRefUrl(c),
    images: Object.fromEntries(c.have.map((s) => [s, kit.imageBase + fileFor(c, s)])),
  })),
  prompts,
};
const template = readFileSync('tools/prompt-matrix.template.html', 'utf8');
writeFileSync(`${dir}/prompt-matrix.html`, template.replace('/*__KIT__*/null', JSON.stringify(data)));
console.log(`wrote ${dir}/PROMPT-MATRIX.md and ${dir}/prompt-matrix.html (${total} prompts, ${haveCount} images in repo)`);
