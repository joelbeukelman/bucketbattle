/**
 * Builds the character prompt matrix from docs/characters/prompt-kit.json:
 *   - docs/characters/PROMPT-MATRIX.md     (every prompt, ready to paste, V7 syntax)
 *   - docs/characters/prompt-matrix.html   (interactive run sheet, published as an Artifact)
 * Usage: pnpm prompts
 */
import { readFileSync, writeFileSync } from 'node:fs';

interface Sheet { id: string; label: string; why: string; style: 'hero' | 'map' | 'prop'; instrument: boolean; text: string; params: string; charRef: 'strong' | 'light' | null }
interface Character { id: string; name: string; genre: string; placeholder?: boolean; look: string; instrument: string }
interface Kit { styleRefs: { hero: string; map: string }; styles: Record<Sheet['style'], string>; sheets: Sheet[]; characters: Character[] }

const dir = 'docs/characters';
const kit: Kit = JSON.parse(readFileSync(`${dir}/prompt-kit.json`, 'utf8'));

/** Style block + character block + sheet block + params. Props skip the outfit. */
function assemble(c: Character, s: Sheet): string {
  const parts = [kit.styles[s.style], s.style === 'prop' ? null : c.look, s.instrument ? c.instrument : null, s.text];
  return `${parts.filter(Boolean).join(', ')} ${s.params}`;
}

const saveAs = (c: Character, s: Sheet) => `char-${c.id}-${s.id}.png`;
const prompts = Object.fromEntries(kit.characters.map((c) => [c.id, Object.fromEntries(kit.sheets.map((s) => [s.id, assemble(c, s)]))]));

// Markdown: resolve style refs; character refs use V7 --oref with a placeholder.
const md = (c: Character, s: Sheet) =>
  prompts[c.id]![s.id]!
    .replaceAll('{HERO_SREF}', kit.styleRefs.hero)
    .replaceAll('{MAP_SREF}', kit.styleRefs.map)
    .replace(/\{CHAR_REF:(strong|light)\}/, (_, w) => `--oref <${c.id} turnaround URL> --ow ${w === 'strong' ? 100 : 40}`);

const lines: string[] = [
  '# Prompt Matrix: starter characters',
  '',
  '_Generated by `pnpm prompts` from `prompt-kit.json`. Edit the JSON, not this file._',
  '',
  `${kit.characters.length} characters × ${kit.sheets.length} sheets = **${kit.characters.length * kit.sheets.length} prompts**. Syntax is Midjourney V7 (\`--oref\` / \`--ow\`); on V6 use \`--cref\` / \`--cw\` instead.`,
  '',
  '## Run order (per character)',
  ...kit.sheets.map((s, i) => `${i + 1}. **${s.label}**: ${s.why}`),
  '',
  `Style references (public URLs, already filled in): hero = REF-005 (${kit.styleRefs.hero}), map = REF-004 (${kit.styleRefs.map}).`,
  '',
  '## Matrix',
  '',
  `| Character | ${kit.sheets.map((s, i) => `${i + 1}. ${s.label}`).join(' | ')} |`,
  `|---|${kit.sheets.map(() => '---').join('|')}|`,
  ...kit.characters.map((c) => `| **${c.id}** ${c.name}${c.placeholder ? ' *(placeholder design)*' : ''} | ${kit.sheets.map((s) => `[\`${c.id}-${s.id}\`](#${c.id}-${s.id})${s.charRef ? ' 🔗' : ''}`).join(' | ')} |`),
  '',
  '🔗 = needs that character\'s turnaround URL as `--oref` (replace `<… turnaround URL>`).',
  '',
  'Save results as `docs/references/images/char-<character>-<sheet>.png`, e.g. `char-01-rap-turnaround.png`.',
  '',
];
for (const c of kit.characters) {
  lines.push(`## ${c.id} · ${c.name}`, '');
  if (c.placeholder) lines.push('> Placeholder design. Replace `look` in prompt-kit.json if you have a reference.', '');
  for (const [i, s] of kit.sheets.entries()) {
    lines.push(`<a id="${c.id}-${s.id}"></a>`, `### ${i + 1}. ${s.label} → \`${saveAs(c, s)}\``, '```', md(c, s), '```', '');
  }
}
writeFileSync(`${dir}/PROMPT-MATRIX.md`, lines.join('\n'));

const data = { styleRefs: kit.styleRefs, sheets: kit.sheets.map(({ id, label, why, charRef }) => ({ id, label, why, charRef })), characters: kit.characters.map(({ id, name, genre, placeholder }) => ({ id, name, genre, placeholder: !!placeholder })), prompts };
const template = readFileSync('tools/prompt-matrix.template.html', 'utf8');
writeFileSync(`${dir}/prompt-matrix.html`, template.replace('/*__KIT__*/null', JSON.stringify(data)));
console.log(`wrote ${dir}/PROMPT-MATRIX.md and ${dir}/prompt-matrix.html (${kit.characters.length * kit.sheets.length} prompts)`);
